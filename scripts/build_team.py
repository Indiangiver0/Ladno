"""Generate and validate project subagent profiles using only Python's stdlib."""

import argparse
import json
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARKER = "Generated by scripts/build_team.py; edit team/roster.json instead."
EXPECTED_DEPARTMENTS = {"product", "finance", "architecture", "frontend", "backend-data", "creative", "qa"}
EXPECTED_COURT = {
    "court-critic": "critic",
    "court-implementation-advocate": "advocate",
    "court-user-advocate": "advocate",
    "court-judge": "judge",
}


def require(condition, message):
    if not condition:
        raise ValueError(message)


def load_roster():
    data = json.loads((ROOT / "team/roster.json").read_text(encoding="utf-8"))
    require(data["schema_version"] == 1, "Unsupported roster version")
    require(data["chief"]["id"] == "chief", "Missing main-chat chief")
    roles = data["roles"]
    require(len(roles) == 25, "Expected exactly 25 subagent roles")
    by_id = {role["id"]: role for role in roles}
    require(len(by_id) == len(roles), "Role IDs must be unique")
    departments = data["departments"]
    require(len(departments) == 7, "Expected seven departments")
    require({dept["id"] for dept in departments} == EXPECTED_DEPARTMENTS, "Unexpected department set")
    membership = []
    for dept in departments:
        members = dept["members"]
        require(len(members) == 3 and len(set(members)) == 3, f"{dept['id']}: expected three distinct members")
        require(dept["head"] in members, f"{dept['id']}: head missing from members")
        require(all(member in by_id for member in members), f"{dept['id']}: unknown member")
        head = by_id[dept["head"]]
        require(head["kind"] == "head" and head["reports_to"] == "chief", f"{dept['id']}: invalid head")
        for member in members:
            role = by_id[member]
            require(role["department"] == dept["id"], f"{member}: mismatched department")
            if member != dept["head"]:
                require(role["kind"] == "specialist" and role["reports_to"] == dept["head"], f"{member}: invalid reporting line")
        membership.extend(members)
    court = data["court"]
    require(court["id"] == "court", "Invalid court ID")
    require(len(court["members"]) == 4 and set(court["members"]) == set(EXPECTED_COURT), "Court requires critic, two advocates and judge")
    for member, kind in EXPECTED_COURT.items():
        require(member in by_id, f"Missing court role {member}")
        role = by_id[member]
        require(role["department"] == "court" and role["kind"] == kind, f"{member}: invalid court role")
        expected_report = "chief" if kind == "judge" else "court-judge"
        require(role["reports_to"] == expected_report, f"{member}: invalid court reporting line")
    membership.extend(court["members"])
    require(len(membership) == len(set(membership)) and set(membership) == set(by_id), "Each role must belong to exactly one unit")
    for role in roles:
        require(re.fullmatch(r"[a-z]+(?:-[a-z]+)*", role["id"]) is not None, f"Invalid role name {role['id']}")
        require(isinstance(role["title"], str) and role["title"].strip(), f"{role['id']}: missing title")
        for field in ("responsibilities", "acceptance"):
            require(isinstance(role[field], list) and role[field], f"{role['id']}: missing {field}")
            require(all(isinstance(item, str) and item.strip() for item in role[field]), f"{role['id']}: invalid {field}")
    return data


def instructions(role, roster):
    lines = [
        f"Ты — {role['title']} ({role['id']}) в команде разработки приложения финансовых расчётов.",
        "Перед работой прочитай AGENTS.md и team/PROTOCOL.md. Выполняй только выданную задачу в рамках своей роли и разрешённых файлов.",
        f"Подчинение по процессу: {role['reports_to']}. Обсуждение со смежными ролями не меняет владельцев файлов и условий приёмки.",
        "Не придумывай требования, выполненные проверки и активных агентов. Не объявляй настройку команды проверкой будущего приложения.",
        "Права и ограничения задаёт родительская сессия; этот профиль не даёт дополнительных разрешений.",
        "",
        "Обязанности:",
        *[f"- {item}" for item in role["responsibilities"]],
        "",
        "Критерии проверки:",
        *[f"- {item}" for item in role["acceptance"]],
    ]
    if role["kind"] == "head":
        dept = next(dept for dept in roster["departments"] if dept["head"] == role["id"])
        specialists = [member for member in dept["members"] if member != role["id"]]
        lines.extend([
            "",
            f"Твои специалисты: {', '.join(specialists)}. Разбей отдельные задачи по их специализации и используй реальные вызовы субагентов.",
            "Передай каждому специалисту его профиль и контекст. При нехватке слотов верни начальнику план запуска специалистов очередями, затем проверь их реальные результаты отдельным этапом.",
            "Не утверждай собственную реализацию. Проверь работу каждого исполнителя и совместимость частей; независимый QA и суд остаются отдельными этапами.",
        ])
    elif role["department"] == "court":
        lines.extend([
            "",
            "Ты независим от авторов проверяемой версии. Если участвовал в её реализации, сообщи начальнику о конфликте и не выполняй эту судебную роль.",
            "Не изменяй продукт и чужие материалы. Работай с зафиксированным пакетом дела, а позицию/решение верни начальнику для протокола.",
            "Первоначальные позиции критика и двух адвокатов независимы до раскрытия. После раскрытия обязателен обмен конкретными возражениями и ответами. Судья читает весь спор и не выступает его стороной.",
            "Используй ID замечаний, тяжесть P0–P3, статус подтверждения и ссылки на доказательства. Не выдумывай спор ради количества участников.",
        ])
    else:
        lines.extend([
            "",
            "Верни результат своему главе: изменения/выводы, доказательства, допущения, ограничения. Не принимай свою работу сам.",
            "Не правь файлы другого исполнителя без нового назначения владельца начальником. При пересечении передай предложение владельцу.",
        ])
    lines.extend([
        "",
        "Формат отчёта: задача и версия; выполненное; доказательства (команда/шаги, ожидание, факт); замечания с ID и приоритетом; оставшиеся вопросы; рекомендуемое следующее действие.",
    ])
    return "\n".join(lines) + "\n"


def expected_files(roster):
    files = {}
    for role in roster["roles"]:
        desc = f"{role['title']}. Используй для задач отдела {role['department']}; роль {role['kind']}."
        body = instructions(role, roster)
        quoted = lambda value: json.dumps(value, ensure_ascii=False)
        native = (
            f"# {MARKER}\n"
            f"name = {quoted(role['id'])}\n"
            f"description = {quoted(desc)}\n"
            f"developer_instructions = {quoted(body)}\n"
        )
        parsed = tomllib.loads(native)
        require(set(parsed) == {"name", "description", "developer_instructions"}, f"Unexpected TOML fields for {role['id']}")
        require(parsed["developer_instructions"] == body, f"Instruction encoding mismatch for {role['id']}")
        markdown = (
            "---\n"
            f"name: {role['id']}\n"
            f"description: {quoted(desc)}\n"
            "---\n\n"
            f"<!-- {MARKER} -->\n\n{body}"
        )
        files[ROOT / ".codex/agents" / f"{role['id']}.toml"] = native
        files[ROOT / ".cursor/agents" / f"{role['id']}.md"] = markdown
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="Generate project profiles; refuse to overwrite unmanaged files")
    mode.add_argument("--check", action="store_true", help="Validate roster and compare installed profiles without writing")
    mode.add_argument("--validate-roster", action="store_true", help="Validate source roster and generated TOML in memory")
    args = parser.parse_args()
    roster = load_roster()
    files = expected_files(roster)
    for rel in ("AGENTS.md", "team/PROTOCOL.md", "team/README.md", "team/templates/task.md", "team/templates/case.md"):
        require((ROOT / rel).is_file(), f"Missing required document: {rel}")
    if args.write:
        # Check all collisions before making any changes. Never delete other agents.
        for path in files:
            if path.exists():
                require(MARKER in path.read_text(encoding="utf-8"), f"Refusing to overwrite unmanaged file: {path}")
        for path, content in files.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    elif args.check:
        for path, content in files.items():
            require(path.is_file(), f"Missing profile: {path}")
            require(path.read_text(encoding="utf-8") == content, f"Profile differs from roster: {path}")
        for folder in (ROOT / ".codex/agents", ROOT / ".cursor/agents"):
            for path in folder.iterdir():
                if path.is_file() and path.suffix in (".toml", ".md") and path not in files:
                    require(MARKER not in path.read_text(encoding="utf-8"), f"Stale generated profile: {path}")
    scope = "roster and generated TOML in memory" if args.validate_roster else "roster and 50 installed profile files"
    print(f"PASS: {scope}; 7 departments x (1 head + 2 specialists), court = 1 critic + 2 advocates + 1 judge")
    print("Models, permissions, global settings and concurrency limits are inherited and unchanged.")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, KeyError, OSError, TypeError) as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        sys.exit(1)
